-- =============================================================
-- 1) USUÁRIOS ADMINISTRATIVOS
-- =============================================================
create table if not exists public.usuarios (
  idusuarios uuid primary key default gen_random_uuid(),
  auth_user_id uuid,
  usu_nome text not null,
  usu_email text not null,
  usu_status text not null default 'Ativo' check (usu_status in ('Ativo', 'Inativo')),
  usu_acessos jsonb not null default '[]'::jsonb,
  usu_pref_opensidebar boolean default true,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

