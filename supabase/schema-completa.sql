alter table public.hospedagens
  add constraint fk_hospedagens_motivo
  foreign key (hos_estadiamotivo) references public.mainhospedagem(idmainhospedagem) on delete set null,
  add constraint fk_hospedagens_modulo
  foreign key (hos_modulo) references public.modulos(idmodulos) on delete set null,
  add constraint fk_hospedagens_status
  foreign key (hos_status) references public.statushospedagem(idstatushospedagem) on delete set null,
  add constraint fk_hospedagens_quarto
  foreign key (hos_quarto) references public.hos_quartos(idhos_quartos) on delete set null;

